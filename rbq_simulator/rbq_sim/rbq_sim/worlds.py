def yaw_to_quat(yaw: float):
    """Yaw (rad about +z) -> (w, x, y, z) quaternion, the Isaac init_state.rot order."""
    return (math.cos(yaw * 0.5), 0.0, 0.0, math.sin(yaw * 0.5))


def get_world(name: str = "empty"):
    if name not in WORLDS:
        raise ValueError(f"Unknown world '{name}'. Options: {list(WORLDS)}")
    w = WORLDS[name]
    print(f"[rbq_sim] world '{name}': {'USD ' + w['usd'] if w['usd'] else 'flat ground'}")
    return w
